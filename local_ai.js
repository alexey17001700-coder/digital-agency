// База знаний: ключевые слова и ответы для разных ролей
const LOCAL_BRAIN = {
    // Общие ответы для всех
    general: [
        { keywords: ['привет', 'здравствуй', 'хай'], answers: ['Привет, Босс!', 'Здравствуй! Чем займемся?', 'На связи. Какие задачи?'] },
        { keywords: ['как дела', 'как ты'], answers: ['Работаю в штатном режиме.', 'Все системы в норме, готов к работе.', 'Отлично, жду задачу!'] },
        { keywords: ['спасибо', 'благодарю'], answers: ['Всегда пожалуйста!', 'Рад помочь, Босс.', 'Обращайся.'] },
        { keywords: ['кто ты', 'что ты умеешь'], answers: ['Я твой цифровой сотрудник. Без API-ключей работаю в базовом режиме.', 'Я ИИ-агент. Пока ключи не введены, использую локальную базу знаний.'] }
    ],
    
    // Специфичные ответы для Хакера
    'Хакер': [
        { keywords: ['код', 'взлом', 'пароль', 'баг', 'ошибка'], answers: ['Обнаружил уязвимость? Давай посмотрим код.', 'Пароли в открытом виде? Это плохо.', 'Попробуй перебрать переменные, может там утечка памяти.', 'Этот баг можно обойти через API.'] }
    ],
    
    // Специфичные ответы для Юриста
    'Юрист': [
        { keywords: ['закон', 'право', 'договор', 'суд', 'незаконно'], answers: ['Это противоречит 152-ФЗ.', 'Нужно составить договор.', 'Тут есть юридические риски.', 'Согласно законодательству, это допустимо.'] }
    ],

    // Специфичные ответы для Оркестратора (Директора)
    'Оркестратор': [
        { keywords: ['план', 'задача', 'делаем', 'проект'], answers: ['Разбиваем задачу на подзадачи. Начинаем с архитектуры.', 'Назначаю ответственных.', 'Сначала план, потом код.', 'Нужно уточнить ТЗ.'] }
    ]
};

// Функция генерации ответа
function generateLocalResponse(agentName, userMessage) {
    const msg = userMessage.toLowerCase();
    let possibleAnswers = [];

    // 1. Ищем ответы конкретно для этого агента
    if (LOCAL_BRAIN[agentName]) {
        LOCAL_BRAIN[agentName].forEach(rule => {
            if (rule.keywords.some(kw => msg.includes(kw))) {
                possibleAnswers.push(...rule.answers);
            }
        });
    }

    // 2. Если не нашли, ищем в общих
    if (possibleAnswers.length === 0) {
        LOCAL_BRAIN.general.forEach(rule => {
            if (rule.keywords.some(kw => msg.includes(kw))) {
                possibleAnswers.push(...rule.answers);
            }
        });
    }

    // 3. Если совсем ничего не подошло - выдаем заглушку
    if (possibleAnswers.length === 0) {
        const defaultReplies = [
            `Я вас понял, Босс. (Локальный режим: нет ключей для глубокого анализа)`,
            `Принято. Для детального ответа нужны API-ключи. Пока работаю на базовой логике.`,
            `Записал задачу. Но без подключения к ИИ могу отвечать только шаблонами.`
        ];
        possibleAnswers = defaultReplies;
    }

    // Выбираем случайный ответ из подходящих
    return possibleAnswers[Math.floor(Math.random() * possibleAnswers.length)];
}
