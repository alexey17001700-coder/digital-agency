// Функция генерации ответа
function generateLocalResponse(agentName, userMessage) {
    const msg = userMessage.toLowerCase();
    let possibleAnswers = [];

    // 1. Ищем ответы конкретно для данного агента
    if (LOCAL_BRAIN[agentName]) {
        LOCAL_BRAIN[agentName].forEach(rule => {
            if (rule.keywords.some(kw => msg.includes(kw))) {
                possibleAnswers.push(...rule.answers);
            }
        });
    }

    // 2. Если не нашли, ищем в общих
    if (possibleAnswers.length === 0) {
        LOCAL_BRAIN.general.forEach(rule => {
            if (rule.keywords.some(kw => msg.includes(kw))) {
                possibleAnswers.push(...rule.answers);
            }
        });
    }

    // 3. Генерация ответа
    if (possibleAnswers.length > 0) {
        const randomReply = possibleAnswers[Math.floor(Math.random() * possibleAnswers.length)];
        return generateDynamicResponse(randomReply, userMessage);
    }

    // 4. Умная заглушка в случае, если ничего не нашлось
    const fallbacks = [
        `Я зафиксировал ваш запрос ("${userMessage}"), но без API-ключей не хватает знаний для анализа. Подключите ИИ.`,
        `Принято. Для детального ответа нужны ключи. Пока работаю на базовой логике.`,
        `Записал задачу в блокнот. Без доступа к нейросети могу лишь предполагать.`
    ];
    return fallbacks[Math.floor(Math.random() * fallbacks.length)];
}

// Функция генерации динамичного ответа (добавляет контекст запроса)
function generateDynamicResponse(baseReply, userMessage) {
    return `${baseReply} (Учёл ваш запрос: "${userMessage}"). Каковы следующие шаги?`;
}
