function toggleAgentDialogue() {
    isAgentDialogueEnabled = !isAgentDialogueEnabled;
    localStorage.setItem('shtabAgentDialogue', isAgentDialogueEnabled ? 'on' : 'off');
    syncAgentDialogueBtn();
}

