/* Сборщик мини-диалога: 4-6 коротких реплик между выбранными агентами.
   Ведущий — Оркестратор (если выбран), иначе первый. Итог — Приемная/Критик/
   Тестировщик/Результат, если они в Совете. Возвращает [{agent, text}]. */
function buildAgentDialogue(agents, topic) {
    const list = (agents || []).filter(a => AGENT_ICONS[a]);
    if (list.length < 2) return [];
    const t = String(topic || 'задача Босса').replace(/\s+/g, ' ').trim().slice(0, 70) || 'задача Босса';
    const L = n => AGENT_DIALOGUE_LINES[n] || AGENT_DIALOGUE_LINES["По умолчанию"];
    const fill = (s, n) => String(s || '').replace(/\{t\}/g, t).replace(/\{n\}/g, n || 'коллеги');

    const lead = list.includes('Оркестратор') ? 'Оркестратор' : list[0];
    const rest = list.filter(a => a !== lead);
    const a1 = rest[0];
    const a2 = rest[1] || null;
    const closer = ['Приемная', 'Критик', 'Тестировщик', 'Результат'].find(a => list.includes(a)) || lead;

    const out = [];
    out.push({ agent: lead, text: fill(L(lead).ask, a1) });
    out.push({ agent: a1, text: fill(L(a1).answer, lead) });
    if (a2) {
        out.push({ agent: a2, text: fill(L(a2).add, a1) });
        out.push({ agent: a1, text: fill(L(a1).add, a2) });
    } else {
        out.push({ agent: lead, text: fill(L(lead).add, a1) });
    }
    if (closer !== a1) out.push({ agent: closer, text: fill(L(closer).verdict, lead) });
    else out.push({ agent: lead, text: fill(L(lead).verdict, a1) });
    return out;
}

